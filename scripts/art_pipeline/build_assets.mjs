// Post-process REVIEWED renders into app assets:
//   art_raw/variants/<id>/<expression>_<mouth>.png -> assets/art/chars/<id>/<expression>_<mouth>.webp (h<=512)
//   art_raw/bases_cropped/<id>.png                 -> assets/art/chars/<id>/neutral_closed.webp when variant missing
//   art_raw/bg/<family>.png                        -> assets/art/bg/<family>.webp (w<=1080, portrait)
// then regenerates assets/art/index.ts (static require map for Metro).
// Run ONLY after the vision review gate — this is the "ships in the APK" step.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'
import { cutout } from './lib/cutout.mjs'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..')
const RAW = path.join(ROOT, 'art_raw')
const OUT = path.join(ROOT, 'assets', 'art')

const charOut = path.join(OUT, 'chars')
const bgOut = path.join(OUT, 'bg')
fs.mkdirSync(charOut, { recursive: true })
fs.mkdirSync(bgOut, { recursive: true })

// characters whose base sheet left a sliver of a second figure at the right
// edge (propagated into variants) — pre-crop to this width fraction so trim
// can then tighten correctly
const EDGE_FIX = { daichi_kansai: 0.93 }

async function toWebp(src, dst, { height, width, quality = 82, edgeFix = null, transparent = false }) {
  let buf = await fs.promises.readFile(src)
  if (edgeFix) {
    const m = await sharp(buf).metadata()
    buf = await sharp(buf).extract({ left: 0, top: 0, width: Math.round(m.width * edgeFix), height: m.height }).toBuffer()
  }
  buf = await sharp(buf).trim({ threshold: 45 }).toBuffer()
  // characters ship as CUTOUTS (user 2026-07-19: "obviously no white
  // background on their picture") — backdrop art stays opaque
  if (transparent) buf = await cutout(buf)
  await sharp(buf)
    .resize({ height, width, fit: 'inside', withoutEnlargement: true })
    .webp({ quality })
    .toFile(dst)
}

const charIds = fs.existsSync(path.join(RAW, 'bases_cropped'))
  ? fs.readdirSync(path.join(RAW, 'bases_cropped')).filter(f => f.endsWith('.png')).map(f => f.replace('.png', ''))
  : []

let frames = 0
for (const id of charIds) {
  const dir = path.join(charOut, id)
  fs.mkdirSync(dir, { recursive: true })
  const vdir = path.join(RAW, 'variants', id)
  const variantFiles = fs.existsSync(vdir) ? fs.readdirSync(vdir).filter(f => f.endsWith('.png')) : []
  for (const f of variantFiles) {
    await toWebp(path.join(vdir, f), path.join(dir, f.replace('.png', '.webp')), { height: 512, edgeFix: EDGE_FIX[id] ?? null, transparent: true })
    frames++
  }
  // the approved base doubles as neutral_closed if the variant pass missed it
  if (!variantFiles.includes('neutral_closed.png')) {
    await toWebp(path.join(RAW, 'bases_cropped', `${id}.png`), path.join(dir, 'neutral_closed.webp'), { height: 512, transparent: true })
    frames++
  }
  console.log(`chars/${id}: ${fs.readdirSync(dir).length} frames`)
}

// scene render -> ambient.ts family key (renders not listed here are spares
// and stay out of the APK). Keys must match ambientTheme() family keys.
const BG_FAMILY = {
  cafe: 'cafe', tatami: 'tatami', kitchen: 'kitchen', bedroom: 'bedroom',
  living_room: 'home', rain: 'porch', classroom: 'school', office: 'office',
  clinic: 'clinic', izakaya: 'eatery', shop: 'shop', street: 'street',
  transit: 'transit', shrine: 'shrine', park: 'nature', water: 'water',
  event: 'event', sports: 'sports', workshop: 'workshop', phone: 'phone',
  default: 'default',
}
let bgCount = 0
for (const [render, family] of Object.entries(BG_FAMILY)) {
  const src = path.join(RAW, 'bg', `${render}.png`)
  if (!fs.existsSync(src)) { console.log(`MISSING bg render: ${render}`); continue }
  await toWebp(src, path.join(bgOut, `${family}.webp`), { width: 1080, height: 1620, quality: 78 })
  bgCount++
  console.log(`bg/${family}.webp <- ${render}`)
}

// ---- static require index (Metro needs literal require() paths) ----
const lines = [
  '// AUTO-GENERATED by scripts/art_pipeline/build_assets.mjs — do not edit by hand.',
  '// Frame map for the illustrated cast + scene backdrops. Missing entries fall',
  '// back to the SVG CharacterAvatar / gradient backdrop at runtime.',
  '',
  'export const ART_CHARS: Record<string, Record<string, number>> = {',
]
for (const id of charIds) {
  const dir = path.join(charOut, id)
  const fs2 = fs.readdirSync(dir).filter(f => f.endsWith('.webp')).sort()
  lines.push(`  ${JSON.stringify(id)}: {`)
  for (const f of fs2) lines.push(`    ${JSON.stringify(f.replace('.webp', ''))}: require('./chars/${id}/${f}'),`)
  lines.push('  },')
}
// facing per character (from the bible) — the app mirrors a figure when its
// baked facing points away from screen center
const BIBLE = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'art_bible.json'), 'utf8'))
lines.push('}', '', "export const ART_FACING: Record<string, 'left' | 'right'> = {")
for (const c of BIBLE.characters) {
  if (charIds.includes(c.id)) lines.push(`  ${JSON.stringify(c.id)}: ${JSON.stringify(c.face === 'camera-left' ? 'left' : 'right')},`)
}
lines.push('}', '', 'export const ART_BG: Record<string, number> = {')
for (const f of fs.readdirSync(bgOut).filter(f => f.endsWith('.webp')).sort()) {
  lines.push(`  ${JSON.stringify(f.replace('.webp', ''))}: require('./bg/${f}'),`)
}
lines.push('}', '')
fs.writeFileSync(path.join(OUT, 'index.ts'), lines.join('\n'))
console.log(`index.ts written — ${frames} char frames, ${bgCount} backgrounds`)
