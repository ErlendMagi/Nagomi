// scripts/build_conversations_bundle.mjs
//
// Reads every conv_*.json in data/conversations/, tokenises each JP line via
// kuromoji so we can populate line.words against the 20k vocab list, and emits
// src/data/conversations_v2.js — a single bundled module the app imports.
//
// Output exports:
//   CONVERSATIONS  array of conversation objects (with line.words filled in)
//   CHARACTERS     map keyed by id, sourced from data/characters.json
//   META           build timestamp + counts
//
// Run with:  node scripts/build_conversations_bundle.mjs
//           or:  npm run build:bundle

import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';
import kuromoji from 'kuromoji';

const __dirname = path.dirname(url.fileURLToPath(import.meta.url));
const NAGOMI    = path.resolve(__dirname, '..');

const CONV_DIR       = path.join(NAGOMI, 'data', 'conversations');
const CHARS_PATH     = path.join(NAGOMI, 'data', 'characters.json');
const WORDS_PATH     = path.join(NAGOMI, 'data', 'vocab', 'words.json');
const OUT_PATH       = path.join(NAGOMI, 'src', 'data', 'conversations_v2.js');
const KUROMOJI_DICT  = path.join(NAGOMI, 'node_modules', 'kuromoji', 'dict');

if (!fs.existsSync(CONV_DIR)) {
  console.error(`no conversations dir at ${CONV_DIR}`);
  process.exit(1);
}
if (!fs.existsSync(KUROMOJI_DICT)) {
  console.error(`kuromoji dict not found at ${KUROMOJI_DICT}. Run: npm install`);
  process.exit(1);
}

const characters = JSON.parse(fs.readFileSync(CHARS_PATH,   'utf-8'));
const words      = JSON.parse(fs.readFileSync(WORDS_PATH,   'utf-8'));
const wordSet    = new Set(words.map(w => w.jp));

console.log('[1/3] loading kuromoji…');
const tokenizer = await new Promise((resolve, reject) => {
  kuromoji.builder({ dicPath: KUROMOJI_DICT }).build((err, t) => err ? reject(err) : resolve(t));
});

console.log('[2/3] reading conversations…');
const files = fs.readdirSync(CONV_DIR)
  .filter(f => f.startsWith('conv_') && f.endsWith('.json'))
  .sort();

const conversations = [];
for (const file of files) {
  const conv = JSON.parse(fs.readFileSync(path.join(CONV_DIR, file), 'utf-8'));
  // Tokenise each JP line, attach line.words.
  for (const line of conv.lines || []) {
    const tokens = tokenizer.tokenize(line.jp || '');
    const seen = new Set();
    for (const tok of tokens) {
      for (const candidate of [tok.basic_form, tok.surface_form]) {
        if (candidate && candidate !== '*' && wordSet.has(candidate)) {
          seen.add(candidate);
        }
      }
    }
    line.words = [...seen];
  }
  conversations.push(conv);
}

// Build character map for fast lookup at runtime.
const charMap = Object.fromEntries(characters.characters.map(c => [c.id, c]));

console.log('[3/3] writing bundle…');
fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true });

const meta = {
  generatedAt: new Date().toISOString(),
  conversationCount: conversations.length,
  characterCount: Object.keys(charMap).length,
};

const body = `// AUTO-GENERATED by scripts/build_conversations_bundle.mjs
// Do not edit by hand — your changes will be overwritten.
// Source of truth: data/conversations/*.json + data/characters.json

export const META = ${JSON.stringify(meta, null, 2)};

export const CHARACTERS = ${JSON.stringify(charMap, null, 2)};

export const CONVERSATIONS = ${JSON.stringify(conversations, null, 2)};
`;

fs.writeFileSync(OUT_PATH, body, 'utf-8');

const kb = (fs.statSync(OUT_PATH).size / 1024).toFixed(1);
console.log(`wrote ${path.relative(NAGOMI, OUT_PATH)}  (${kb} KB)`);
console.log(`  ${conversations.length} conversations · ${Object.keys(charMap).length} characters`);
