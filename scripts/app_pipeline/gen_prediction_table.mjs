// M5 prediction table generator — forward-simulates a FRESH learner through
// the REAL engine (identical wiring to scripts/app_pipeline/simulate.ts:
// scheduler + picker + graduation against the real corpus in content.db) for
// a sweep of minutes-per-day tracks, recording {day, heard, graduated} at
// ~30-day checkpoints out to 730 days.
//
// The app never simulates on-device (too heavy): src/engine/prediction.ts
// interpolates between these tracks — piecewise-linear in minutes and days —
// and anchors the curve to the user's current heard-count. Locked: the curve
// shape comes from the real engine, never a formula.
//
// Run: npx tsx scripts/app_pipeline/gen_prediction_table.mjs
// (tsx, not node — this file imports the app's TypeScript engine modules)
// Output: assets/prediction_table.json (bundled by Metro as a source module).

import { DatabaseSync } from 'node:sqlite'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { Scheduler, createWordState } from '../../src/core/scheduler'
import { pickNextConversation } from '../../src/core/picker'
import { defaultGraduationSettings, isGraduated } from '../../src/core/graduation'
import { SRS_CONFIG } from '../../src/core/config'
import { ciTargetFor } from '../../src/core/ci'

// extended to the 8h/day planning ceiling (the goal planner inverts this table)
const MINUTES_TRACKS = [10, 20, 30, 45, 60, 90, 120, 180, 240, 360, 480]
const HORIZON_DAYS = 730
const STEP_DAYS = 30

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..')
const db = new DatabaseSync(path.join(ROOT, 'data', 'derived', 'content.db'))

// ---- load corpus into memory (same shape as simulate.ts) ----
console.error('loading corpus...')
const convRows = db.prepare('SELECT conv_id, ord, duration_sec, line_count FROM conversations ORDER BY ord').all()
const convById = new Map(convRows.map(r => [r.conv_id, r]))
const wordsByConv = new Map()
const convsByWord = new Map()
for (const row of db.prepare('SELECT conv_id, word_id FROM conv_words').all()) {
  if (!wordsByConv.has(row.conv_id)) wordsByConv.set(row.conv_id, [])
  wordsByConv.get(row.conv_id).push(row.word_id)
  if (!convsByWord.has(row.word_id)) convsByWord.set(row.word_id, [])
  convsByWord.get(row.word_id).push(row.conv_id)
}
console.error(`corpus: ${convRows.length} convs`)

const index = {
  convsContaining(wordIds) {
    const out = new Map()
    for (const w of wordIds) {
      for (const c of convsByWord.get(w) ?? []) {
        if (!out.has(c)) out.set(c, [])
        out.get(c).push(w)
      }
    }
    return out
  },
  convMeta(convId) {
    const r = convById.get(convId)
    return { convId, ord: r.ord, durationSec: r.duration_sec }
  },
  nextUnheard(afterOrd, exclude) {
    for (const r of convRows) {
      if (r.ord > afterOrd && !exclude.has(r.conv_id)) return { convId: r.conv_id, ord: r.ord, durationSec: r.duration_sec }
    }
    return null
  },
  leastRecentlyPlayed() { return [] },
}

// checkpoint days: 0 (fresh state), every STEP_DAYS, plus the horizon itself
const checkpointDays = new Set()
for (let d = STEP_DAYS; d <= HORIZON_DAYS; d += STEP_DAYS) checkpointDays.add(d)
checkpointDays.add(HORIZON_DAYS)

/** simulate one minutes-per-day track; returns [day, heard, graduated][] */
function simulateTrack(minutesPerDay) {
  const sched = new Scheduler()
  const grad = defaultGraduationSettings()
  const states = new Map()
  const lastPlayed = new Map()
  let frontierOrd = 0
  let lastSessionAt = null
  const start = new Date('2026-08-01T08:00:00')
  const points = [[0, 0, 0]]

  // comprehensible-input tracking — MUST mirror the app's SessionRecorder so
  // the forecast table is generated by the same picker the user experiences
  // (calculator-integrity requirement, 2026-07-15)
  const CI_REPS = SRS_CONFIG.picker.ciComfort.knownReps
  const ciKnownByConv = new Map()
  let ciKnownWords = 0
  const ciRatioOf = (convId) => {
    const total = wordsByConv.get(convId)?.length ?? 0
    if (total <= 0) return undefined
    return Math.min(1, (ciKnownByConv.get(convId) ?? 0) / total)
  }

  for (let day = 0; day < HORIZON_DAYS; day++) {
    const now = new Date(start.getTime() + day * 86_400_000)
    // 4AM materialization: today's due set is FIXED at day start (locked rule)
    const dueWeights = new Map()
    for (const [id, st] of states) {
      const w = sched.duenessWeight(st, now)
      if (w >= 1) dueWeights.set(id, w)
    }
    // reinforcement mode input: heard-but-shallow words
    const inFlightWords = new Map()
    for (const [id, st] of states) {
      if (st.totalReps > 0 && st.totalReps < 10) inFlightWords.set(id, 10 - st.totalReps)
    }

    let budgetSec = minutesPerDay * 60
    let guard = 0
    while (budgetSec > 0 && guard++ < 500) {
      const pick = pickNextConversation(index, {
        now, dueWeights, lastPlayed, frontierOrd, inFlightWords,
        ciRatioOf, ciTarget: ciTargetFor(ciKnownWords),
      })
      if (!pick) break
      const meta = index.convMeta(pick.convId)
      const words = wordsByConv.get(pick.convId) ?? []
      const lineCount = convById.get(pick.convId).line_count
      const perLine = Math.max(1, Math.ceil(words.length / Math.max(1, lineCount)))
      const sessionTime = new Date(now.getTime() + (minutesPerDay * 60 - budgetSec) * 1000)
      for (let li = 0, wi = 0; li < lineCount; li++) {
        for (let k = 0; k < perLine && wi < words.length; k++, wi++) {
          const id = words[wi]
          const st = states.get(id) ?? createWordState(id, sessionTime)
          const prevReps = st.totalReps
          const r = sched.hear(st, sessionTime, lastSessionAt)
          states.set(id, r.state)
          if (prevReps < CI_REPS && r.state.totalReps >= CI_REPS) {
            ciKnownWords += 1
            for (const c of convsByWord.get(id) ?? []) {
              ciKnownByConv.set(c, (ciKnownByConv.get(c) ?? 0) + 1)
            }
          }
          if (r.kind === 'first_of_day') dueWeights.delete(id)
        }
      }
      lastPlayed.set(pick.convId, now.getTime())
      frontierOrd = Math.max(frontierOrd, meta.ord)
      budgetSec -= meta.durationSec
    }
    lastSessionAt = new Date(now.getTime() + minutesPerDay * 60 * 1000)

    const dayN = day + 1
    if (checkpointDays.has(dayN)) {
      let graduated = 0
      for (const [, st] of states) {
        if (isGraduated(st, sched.daysSinceFirstHeard(st, now), grad)) graduated++
      }
      points.push([dayN, states.size, graduated])
    }
  }
  return points
}

const tracks = []
for (const minutes of MINUTES_TRACKS) {
  const t0 = Date.now()
  const points = simulateTrack(minutes)
  const last = points[points.length - 1]
  tracks.push({ minutes, points })
  console.error(`  [${minutes} min/day → heard ${last[1]}, graduated ${last[2]} at day ${last[0]} — ${((Date.now() - t0) / 1000).toFixed(1)}s]`)
}

const grad = defaultGraduationSettings()
const table = {
  generatedAt: new Date().toISOString().slice(0, 10),
  graduation: grad,
  horizonDays: HORIZON_DAYS,
  stepDays: STEP_DAYS,
  tracks,
}

const outPath = path.join(ROOT, 'assets', 'prediction_table.json')
fs.writeFileSync(outPath, JSON.stringify(table))
console.error(`wrote ${outPath} (${fs.statSync(outPath).size} bytes)`)
